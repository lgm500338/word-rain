/**
 * De-conjugates adnominal (관형사형) and common verbal endings
 * back to standard dictionary lemma (기본형: -다).
 * e.g. '혼난' -> '혼나다', '화난' -> '화나다', '예쁜' -> '예쁘다', '먹은' -> '먹다', '혼나는' -> '혼나다'
 */
export function getVerbStemCandidates(word: string): string[] {
  const stems: string[] = [];
  if (word.length < 2) return stems;

  const lastChar = word[word.length - 1];
  const lastCode = lastChar.charCodeAt(0);
  if (lastCode < 0xac00 || lastCode > 0xd7a3) return stems;

  const finalIdx = (lastCode - 0xac00) % 28;
  const prefix = word.slice(0, -1);

  // 1. Ending with ㄴ 받침 (관형사형 -ㄴ: 혼난 -> 혼나다, 예쁜 -> 예쁘다, 화난 -> 화나다, 착한 -> 착하다)
  if (finalIdx === 4) {
    const strippedChar = String.fromCharCode(lastCode - 4);
    stems.push(prefix + strippedChar + '다');
  }

  // 2. Ending with 은 (먹은 -> 먹다, 좋은 -> 좋다, 높은 -> 높다)
  if (lastChar === '은' && word.length >= 2) {
    stems.push(word.slice(0, -1) + '다');
  }

  // 3. Ending with 는 (혼나는 -> 혼나다, 먹는 -> 먹다, 가는 -> 가다)
  if (lastChar === '는' && word.length >= 2) {
    stems.push(word.slice(0, -1) + '다');
  }

  // 4. Ending with ㄹ 받침 (관형사형 -ㄹ: 혼날 -> 혼나다, 갈 -> 가다)
  if (finalIdx === 8) {
    const strippedChar = String.fromCharCode(lastCode - 8);
    stems.push(prefix + strippedChar + '다');
  }

  // 5. Ending with 던 (회상 관형사형: 혼나던 -> 혼나다, 먹던 -> 먹다)
  if (lastChar === '던' && word.length >= 2) {
    stems.push(word.slice(0, -1) + '다');
  }

  return stems;
}

/**
 * Checks whether an input string is an authentic Korean word in the dictionary
 * or a valid real base word with grammatical particle attached,
 * or a valid conjugated verb/adjective modifier form.
 */
export function isValidKoreanWord(input: string, customAccepted?: string[]): boolean {
  const clean = input.trim();
  if (!clean) return false;

  // 1. Check against word-specific custom accepted list (if provided)
  if (customAccepted && customAccepted.some((w) => w === clean)) {
    return true;
  }

  // 2. Numbers / Years (e.g. '2024', '2025년', etc.)
  if (/^\d{4}(년)?$/.test(clean)) {
    return true;
  }

  // 3. Direct dictionary membership
  if (VALID_KOREAN_WORDS.has(clean)) {
    return true;
  }

  // 4. Check stripped base word (e.g. '언니가' -> '언니', '사과를' -> '사과', '언니는' -> '언니', '발발이' -> '발발')
  const base = stripParticle(clean);
  if (base !== clean && VALID_KOREAN_WORDS.has(base)) {
    return true;
  }

  // 5. Check verb / adjective conjugation back to standard lemma (-다)
  // e.g. '혼난' -> '혼나다', '예쁜' -> '예쁘다', '화난' -> '화나다', '먹은' -> '먹다'
  const verbStems = getVerbStemCandidates(clean);
  for (const stem of verbStems) {
    if (VALID_KOREAN_WORDS.has(stem)) {
      return true;
    }
  }

  return false;
}

let isDictionaryLoading = false;
let isDictionaryLoaded = false;

/**
 * Loads the full 350,000+ words National Institute of Korean Language
 * (국립국어원 표준국어대사전) dictionary from /korean_dict.txt in the background.
 */
export async function loadFullKoreanDictionary(): Promise<void> {
  if (isDictionaryLoaded || isDictionaryLoading) return;
  isDictionaryLoading = true;

  try {
    const response = await fetch(`${import.meta.env.BASE_URL}korean_dict.txt`);
    if (!response.ok) {
      console.warn('Failed to load /korean_dict.txt:', response.status);
      isDictionaryLoading = false;
      return;
    }
    const text = await response.text();
    const lines = text.split('\n');
    let addedCount = 0;
    for (let i = 0; i < lines.length; i++) {
      const word = lines[i].trim();
      if (word && !VALID_KOREAN_WORDS.has(word)) {
        VALID_KOREAN_WORDS.add(word);
        addedCount++;
      }
    }
    isDictionaryLoaded = true;
    isDictionaryLoading = false;
    console.log(`[Dictionary] Successfully loaded ${addedCount} additional standard Korean words. Total: ${VALID_KOREAN_WORDS.size}`);
  } catch (err) {
    console.error('[Dictionary] Error loading full Korean dictionary:', err);
    isDictionaryLoading = false;
  }
}

// Automatically trigger background loading in the browser
if (typeof window !== 'undefined') {
  loadFullKoreanDictionary();
}
